-- order_items.supplier + delivery_days — снимок реального поставщика/склада и
-- срока доставки позиции НА МОМЕНТ ЗАКАЗА (переносятся из строки корзины).
--
-- Зачем: письмо магазину «Заказ ОПЛАЧЕН» строится из order_items (lib/payments/settle.ts).
-- В таблице этих полей не было, поэтому в письме колонки «Поставщик» и «Срок»
-- всегда приходили пустыми («—») — менеджер не видел, у кого и за сколько дней
-- заказывать. Корзина (cart_items) эти данные хранила, но при оформлении заказа
-- они терялись.
--
-- Колонки NULLABLE: старые заказы снимка не имеют — у них так и останется «—».
--
-- ВАЖНО: применить ДО деплоя нового кода (новый код пишет эти колонки при
-- создании заказа). На непромигрированной БД оформление заказа упадёт.
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS supplier text;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS delivery_days integer;
